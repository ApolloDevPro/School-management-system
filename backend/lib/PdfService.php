    private static function amountInWords(float $amount, string $currency = 'Ugx'): string
    {
        $units = ['', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine'];
        $teens = ['Ten', 'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen', 'Seventeen', 'Eighteen', 'Nineteen'];
        $tens = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];

        $convert = function (int $n) use ($units, $teens, $tens, &$convert): string {
            if ($n === 0) return '';
            if ($n < 10) return $units[$n];
            if ($n < 20) return $teens[$n - 10];
            if ($n < 100) return $tens[(int)($n / 10)] . ($n % 10 !== 0 ? ' ' . $units[$n % 10] : '');
            if ($n < 1000) return $units[(int)($n / 100)] . ' Hundred' . ($n % 100 !== 0 ? ' and ' . $convert($n % 100) : '');
            return $convert((int)($n / 1000)) . ' Thousand' . ($n % 1000 !== 0 ? ' ' . $convert($n % 1000) : '');
        };

        $whole = (int)$amount;
        $cents = (int)round(($amount - $whole) * 100);

        $words = $whole === 0 ? 'Zero' : $convert($whole);
        $words .= ' ' . strtoupper($currency);

        if ($cents > 0) {
            $words .= ' and ' . ($cents < 10 ? '0' : '') . $cents . ' cents';
        }

        return $words . ' only.';
    }

