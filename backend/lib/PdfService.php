    public static function html(string $title, string $body, array $opts = []): string
    {
        $school = school_row() ?? [];
        $currency = $school['currency_symbol'] ?? 'Ugx';
        $logo = $school['logo_path'] ? '<img src="'.e($school['logo_path']).'" height="34" alt="logo" style="margin-right:12px">' : '';
        $footerText = $opts['footer'] ?? (Setting::get((int)$school['id'] ?? 1, 'reporting.report_card_footer', 'Generated by SSMS') ?? 'Generated by SSMS');

        return '<!doctype html><html><head><meta charset="utf-8"><title>'.e($title).'</title>'
            .'<style>'.self::CSS.'</style></head><body>'
            .'<div class="pdf-header">'
            .'<div><div class="pdf-title">'.$logo.e($title).'</div>'
            .'<div class="pdf-sub">'.e($school['name'] ?? APP_NAME).' &middot; '.e(date('d M Y')).'</div></div>'
            .'<div class="school-info">'.e($school['name'] ?? '').'<br>'
            .e($school['physical_address'] ?? '').'<br>'
            .e($school['phone'] ?? '').' &middot; '.e($school['email'] ?? '').'</div>'
            .'</div>'
            .$body
            .'<div class="footer">'.e($footerText).' &middot; Page <span class="page-number"></span></div>'
            .'</body></html>';
    }

    public static function output(string $html, string $filename = 'document.pdf', bool $download = true): void
    {
        $pdf = self::renderDompdf($html);
        if ($pdf !== null) {
            if ($download) {
                header('Content-Type: application/pdf');
                header('Content-Disposition: attachment; filename="'.basename($filename).'"');
                header('Cache-Control: no-cache');
            }
            echo $pdf;
            return;
        }

        if ($download) {
            header('Content-Type: text/html; charset=utf-8');
            header('Content-Disposition: attachment; filename="'.basename($filename, '.pdf').'.html"');
            header('Cache-Control: no-cache');
        }
        echo '<!doctype html><html><head><meta charset="utf-8"><title>'.e($filename).'</title>'
            .'<style>body{font-family:system-ui,sans-serif;padding:24px;background:#f1f5f9}'
            .'.notice{border:1px solid #e2e8f0;background:#fff;border-radius:10px;padding:24px;max-width:760px;margin:40px auto;box-shadow:0 4px 20px rgba(15,23,42,.1)}'
            .'.notice h2{margin-top:0;color:#1e3a8a}.notice p{color:#64748b}.notice code{background:#eef2ff;padding:2px 6px;border-radius:4px}</style>'
            .'</head><body><div class="notice"><h2>PDF Export</h2>'
            .'<p>Real PDF generation (Dompdf/TCPDF) is wired through <code>PdfService::output()</code>. '
            .'Install <code>dompdf/dompdf</code> via Composer and render <code>$html</code> here.</p>'
            .'<p><strong>Filename:</strong> '.e($filename).'</p>'
            .'<p>To preview the formatted document now, open this page in your browser and press Ctrl+P (Print to PDF).</p>'
            .'</div></body></html>';
    }

    private static function renderDompdf(string $html): ?string
    {
        $autoload = __DIR__ . '/../../vendor/autoload.php';
        if (!is_file($autoload)) {
            return null;
        }
        require $autoload;

        if (!class_exists(\Dompdf\Dompdf::class)) {
            return null;
        }

        $dompdf = new \Dompdf\Dompdf();
        $dompdf->loadHtml($html);
        $dompdf->setPaper('A4', 'portrait');
        $dompdf->render();
        return $dompdf->output();
    }

